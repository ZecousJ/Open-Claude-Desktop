// Regenerates electron/skills/api-image-files.ts from vendor/api-image
// (https://github.com/yc-duan/api-image, MIT): the skill's files as strings,
// so the desktop app and the runner carry them without packaging changes.
// Run: node scripts/vendor-api-image.mjs
import fs from "node:fs";
import path from "node:path";

const root = "vendor/api-image";
const keep = (rel) =>
  rel === "SKILL.md" ||
  rel === "LICENSE" ||
  rel.startsWith("agents/") ||
  (rel.startsWith("scripts/") && rel.endsWith(".py"));
const files = {};
const walk = (dir) => {
  for (const entry of fs.readdirSync(path.join(root, dir), {
    withFileTypes: true,
  })) {
    const rel = dir ? `${dir}/${entry.name}` : entry.name;
    if (entry.isDirectory()) walk(rel);
    else if (keep(rel))
      files[rel] = fs.readFileSync(path.join(root, rel), "utf8");
  }
};
walk("");
const sorted = Object.fromEntries(
  Object.entries(files).sort(([a], [b]) => a.localeCompare(b)),
);
fs.mkdirSync("electron/skills", { recursive: true });
fs.writeFileSync(
  "electron/skills/api-image-files.ts",
  `// Generated by scripts/vendor-api-image.mjs from vendor/api-image (yc-duan/api-image @ 5d53535, MIT). Do not edit.\n` +
    `export const apiImageFiles: Record<string, string> = ${JSON.stringify(sorted, null, 2)};\n`,
);
console.log(Object.keys(sorted).join("\n"));
