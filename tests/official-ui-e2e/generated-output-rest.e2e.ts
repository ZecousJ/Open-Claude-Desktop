import assert from "node:assert/strict";
import { once } from "node:events";
import fs from "node:fs";
import http from "node:http";
import type { AddressInfo } from "node:net";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import vm from "node:vm";
import { build } from "esbuild";
import ts from "typescript";
import { Engine } from "../../electron/engine/engine";
import { resolveRuntime } from "../../electron/engine/runtime";
import {
  organizationUuid,
  type AdapterContext,
} from "../../electron/official-ui/api/context";
import { createApiAdapter } from "../../electron/official-ui/api/index";
import { Store } from "../../electron/store/store";
import { openPolicy } from "../../shared/client-policy";
import type { AppEvent } from "../../shared/types";
import {
  FAKE_KEY,
  MODEL,
  MockResponses,
  findTool,
  functionCall,
  message,
} from "../spikes/harness";

const owner = "f019-rest-owner";
const conversation = "11111111-1111-4111-8111-111111111111";
const assistant = "33333333-3333-4333-8333-333333333333";
const prompt = "Create report.md for me.";
const filename = "report.md";
const fileText = "# Generated report 中文\n";
const shellFile = "notes.txt";
const shellText = "Generated by shell\n";
const artifact =
  '<antArtifact identifier="rest-report" type="text/markdown" title="REST report">\n# Inline report 中文\n</antArtifact>';

test(
  "native REST sends to the local engine and restores the inline artifact and generated snapshot",
  { timeout: 60_000 },
  async (t) => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), "claudex-f019-rest-"));
    const profile = path.join(root, "profile");
    const upstream = new MockResponses();
    let store = new Store(profile);
    let engine: Engine | undefined;
    let server: http.Server | undefined;
    t.after(async () => {
      await engine?.stop();
      store.flush();
      if (server) {
        server.closeAllConnections();
        await new Promise<void>((resolve) => server!.close(() => resolve()));
      }
      await upstream.close();
      fs.rmSync(root, { recursive: true, force: true });
    });
    await upstream.start();
    let calls = 0;
    upstream.script = (body) => {
      const tool = findTool(body, (name) => name === "apply_patch");
      if (!JSON.stringify(body.input).includes(prompt))
        return [message("REST report")];
      const hasOutput = (callId: string) =>
        body.input.some(
          (item: { type: string; call_id: string }) =>
            item.type.endsWith("_call_output") && item.call_id === callId,
        );
      if (hasOutput("report_shell")) return [message(artifact, "msg_report")];
      if (hasOutput("report_patch")) {
        const shell = findTool(body, (name) =>
          ["exec_command", "shell_command", "shell"].includes(name),
        );
        assert.ok(shell, "the engine offered a shell tool");
        const command = `printf '%s\\n' '${shellText.trimEnd()}' > '${shellFile}'`;
        return [
          functionCall(shell, "report_shell", {
            ...(shell.name === "exec_command" ? { cmd: command } : { command }),
            description: "Save the fixture notes",
          }),
        ];
      }
      assert.equal(tool?.type, "custom");
      calls++;
      return [
        {
          type: "custom_tool_call",
          id: "fc_report",
          call_id: "report_patch",
          name: tool!.name,
          ...(tool!.namespace ? { namespace: tool!.namespace } : {}),
          input: `*** Begin Patch\n*** Add File: ${filename}\n+${fileText.trimEnd()}\n*** End Patch`,
          status: "completed",
        },
      ];
    };
    store.settings.providers = [
      {
        id: "fixture",
        name: "Local F019 fixture",
        protocol: "responses",
        baseUrl: upstream.url,
        model: MODEL,
        models: [MODEL],
      },
    ];
    store.settings.activeProviderId = "fixture";
    const service = path.join(root, "provider-service.cjs");
    await build({
      entryPoints: ["server/provider-service.ts"],
      bundle: true,
      platform: "node",
      format: "cjs",
      target: "node22",
      outfile: service,
    });
    const listeners = new Set<(event: AppEvent) => void>();
    engine = new Engine(
      store,
      resolveRuntime(process.env.CLAUDEX_F019_RUNTIME_RESOURCES),
      () => FAKE_KEY,
      (event) => {
        for (const listener of listeners) listener(event);
      },
      service,
    );
    engine.policy = () => openPolicy;
    engine.trustEveryWorkspace = true;
    let identity = {};
    let sends = 0;
    const ctx: AdapterContext = {
      account: () => ({
        id: owner,
        name: "F019",
        email: "fixture@example.invalid",
      }),
      sessionIdentity: () => identity,
      stateDirectory: () => profile,
      settings: () => store.settings,
      root: path.resolve("build/official-ui"),
      snapshot: async () => ({
        artifactLibrary: { version: 1, copies: [], pinned: [] },
        dismissedBackgroundTasks: [],
        artifactShares: [],
        settings: store.settings,
        conversations: structuredClone(store.conversations),
        projects: structuredClone(store.projects),
        engine: engine!.state,
        approvals: [],
        platform: process.platform,
        replyFeedback: {},
      }),
      listConversations: async () => structuredClone(store.conversations),
      loadConversation: async (id) => {
        const row = store.conversations.find((c) => c.id === id);
        return row && structuredClone(row);
      },
      onEvent(listener) {
        listeners.add(listener);
        return () => {
          listeners.delete(listener);
        };
      },
      modelCatalog: async () => ({
        defaultModel: MODEL,
        items: [
          {
            id: MODEL,
            displayName: MODEL,
            description: "",
            badges: [],
            sort: 0,
            hidden: false,
            isDefault: true,
            usageHint: "",
          },
        ],
      }),
      appVersion: "test",
      log() {},
      async call(method, ...args) {
        if (method === "readGeneratedFile")
          return engine!.blobs.read(args[0] as string).toString("base64");
        assert.equal(method, "send");
        sends++;
        return engine!.send(args[0] as Parameters<Engine["send"]>[0]);
      },
    };
    let adapter = createApiAdapter(ctx, {
      scoped: true,
      restCompletion: "native",
    });
    const ui = path.join(ctx.root, "ui");
    server = http.createServer((req, res) => {
      const pathname = new URL(req.url ?? "/", "http://localhost").pathname;
      if (pathname === "/app.js") {
        res
          .writeHead(200, { "content-type": "text/javascript" })
          .end('import("/assets/v1/index-BJJTYFi2.js");');
        return;
      }
      const asset = path.resolve(ui, "." + pathname);
      const assetTypes: Record<string, string> = {
        ".js": "text/javascript",
        ".css": "text/css",
        ".json": "application/json",
        ".svg": "image/svg+xml",
        ".png": "image/png",
        ".woff2": "font/woff2",
      };
      if (
        pathname.startsWith("/assets/") &&
        asset.startsWith(ui + path.sep) &&
        fs.existsSync(asset) &&
        fs.statSync(asset).isFile()
      ) {
        res.writeHead(200, {
          "content-type":
            assetTypes[path.extname(asset)] ?? "application/octet-stream",
        });
        fs.createReadStream(asset).pipe(res);
        return;
      }
      if (
        pathname === "/" ||
        pathname === "/new" ||
        /^\/chat\/[^/]+$/.test(pathname)
      ) {
        res
          .writeHead(200, { "content-type": "text/html" })
          .end(fs.readFileSync(path.join(ui, "index.html")));
        return;
      }
      void adapter(req, res).then(
        (handled) => {
          if (!handled) res.writeHead(404).end();
        },
        (error) => res.destroy(error),
      );
    });
    server.listen(0, "127.0.0.1");
    await once(server, "listening");
    const origin = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
    if (process.env.CLAUDEX_F019_PLAYWRIGHT) {
      const driver = "./generated-output-rest-browser.mjs";
      const { verifyOriginalRestChat } = await import(driver);
      await verifyOriginalRestChat({
        origin,
        prompt,
        fileText,
        shellText,
        async reopen(id: string) {
          await engine!.stop();
          for (const item of store.conversation(id).turns[0].items)
            for (const file of item.generatedFiles ?? [])
              fs.unlinkSync(file.path);
          store = new Store(profile);
          identity = {};
          adapter = createApiAdapter(ctx, {
            scoped: true,
            restCompletion: "native",
          });
        },
      });
      assert.equal(sends, 1);
      return;
    }
    const org = `${origin}/api/organizations/${organizationUuid(owner)}`;
    const chat = `${org}/chat_conversations/${conversation}`;
    const submission = {
      prompt,
      model: MODEL,
      tools: [],
      attachments: [],
      files: [],
      sync_sources: [],
      rendering_mode: "messages",
      turn_message_uuids: {
        human_message_uuid: "22222222-2222-4222-8222-222222222222",
        assistant_message_uuid: assistant,
      },
      completion_request_id: "44444444-4444-4444-8444-444444444444",
      create_conversation_params: {
        name: "",
        model: MODEL,
        include_conversation_preferences: true,
        is_temporary: false,
        chat_memory_mode: "disabled",
      },
    };
    const send = () =>
      fetch(chat + "/completion", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify(submission),
        signal: AbortSignal.timeout(30_000),
      });
    let markThreadStarted = () => {};
    let releaseThreadStart = () => {};
    const threadStarted = new Promise<void>((resolve) => { markThreadStarted = resolve; });
    const threadReleased = new Promise<void>((resolve) => { releaseThreadStart = resolve; });
    const ensureThread = engine.ensureThread.bind(engine);
    engine.ensureThread = async (...args) => {
      markThreadStarted();
      await threadReleased;
      return ensureThread(...args);
    };
    const historyUrl = chat +
      "?tree=True&rendering_mode=messages&render_all_tools=true&consistency=strong";
    const submissionResponse = send();
    try {
      await Promise.race([threadStarted, submissionResponse.then(response => {
        assert.equal(response.status, 200);
        return threadStarted;
      })]);
      const pending = await fetch(historyUrl, { signal: AbortSignal.timeout(5000) });
      assert.equal(pending.status, 200);
      const history = await pending.json();
      assert.deepEqual(history.chat_messages.map((row: { uuid: string }) => row.uuid), [
        submission.turn_message_uuids.human_message_uuid, assistant,
      ]);
      assert.equal(history.current_leaf_message_uuid, assistant);
    } finally {
      releaseThreadStart();
    }
    const response = await submissionResponse;
    assert.equal(response.status, 200);
    assert.match(response.headers.get("content-type")!, /^text\/event-stream/);
    const wire = await response.text();
    const events = wire
      .trim()
      .split("\n\n")
      .map((frame) =>
        JSON.parse(
          frame
            .split("\n")
            .find((line) => line.startsWith("data: "))!
            .slice(6),
        ),
      );
    const turn = store.conversation(conversation).turns[0];
    assert.equal(
      events.at(-1).type,
      "message_stop",
      JSON.stringify({ events, turn }),
    );
    assert.equal(calls, 1);
    assert.equal(sends, 1);
    assert.equal(
      turn.items.find((item) => item.type === "outputFiles")
        ?.generatedFiles?.[0]?.name,
      shellFile,
    );
    assert.equal(
      turn.items.find((item) => item.type === "fileChange")?.status,
      "completed",
    );
    assert.equal(
      events
        .filter((event) => event.delta?.type === "text_delta")
        .map((event) => event.delta.text)
        .join(""),
      artifact,
    );
    const delivery = events.find(
      (event) =>
        event.content_block?.name === "SendUserFile" &&
        event.content_block?.type === "tool_result",
    ).content_block;
    const files: { path: string; file_uuid: string; size: number }[] =
      delivery.attachments;
    const contents = new Map([
      [filename, fileText],
      [shellFile, shellText],
    ]);
    assert.equal(files.length, contents.size);
    for (const file of files) {
      const expected = contents.get(path.basename(file.path));
      assert.equal(fs.readFileSync(file.path, "utf8"), expected);
      const read = await fetch(`${org}/files/${file.file_uuid}/contents`);
      assert.equal(read.status, 200);
      assert.equal(await read.text(), expected);
      fs.unlinkSync(file.path);
    }
    const originalModule = path.join(
      ctx.root,
      "ui/assets/v1/shared-11-Dzm8qD_O.js",
    );
    const source = ts.createSourceFile(
      originalModule,
      fs.readFileSync(originalModule, "utf8"),
      ts.ScriptTarget.Latest,
      true,
      ts.ScriptKind.JS,
    );
    const consumer = ["IY", "rI", "sX", "fq", "bD", "iC"].map((name) => {
      const node = source.statements.find(
        (node) => ts.isFunctionDeclaration(node) && node.name?.text === name,
      );
      assert.ok(node, name);
      return node.getText(source);
    });
    const blocks = events.flatMap((event) =>
      event.content_block ? [event.content_block] : [],
    );
    const cards = vm.runInNewContext(`${consumer.join("\n")}\nIY(blocks)`, {
      blocks,
    });
    assert.deepEqual(
      JSON.parse(JSON.stringify(cards)),
      files.map((file) => ({
        path: file.path,
        deliveryKind: "attachment",
        fileUuid: file.file_uuid,
        display: "attach",
        sizeBytes: file.size,
      })),
    );

    await engine.stop();
    store = new Store(profile);
    identity = {};
    adapter = createApiAdapter(ctx, { scoped: true, restCompletion: "native" });
    for (const file of files) {
      const read = await fetch(`${org}/files/${file.file_uuid}/contents`);
      assert.equal(read.status, 200);
      assert.equal(await read.text(), contents.get(path.basename(file.path)));
    }
    const history = await fetch(historyUrl);
    assert.equal(history.status, 200);
    const saved = await history.json();
    assert.equal(saved.current_leaf_message_uuid, assistant);
    assert.equal(
      saved.chat_messages[1].content.find(
        (block: { type: string }) => block.type === "text",
      ).text,
      artifact,
    );
    assert.deepEqual(
      saved.chat_messages[1].content.find(
        (block: { name?: string; type: string }) =>
          block.name === "SendUserFile" && block.type === "tool_result",
      ),
      delivery,
    );
    assert.equal((await send()).status, 409);
    assert.equal(sends, 1);
  },
);
