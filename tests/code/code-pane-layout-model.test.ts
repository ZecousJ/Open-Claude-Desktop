import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import {
  initialCodeLayout,
  openCodeTile,
  moveCodeTileToEdge,
  codeTileIds,
  resolvedCodeWeights,
  resolveCodeLayout,
  resizeCodeDivider,
  removeCodeTile,
  captureCodePlacement,
  type CodeLayout,
  type CodeNode,
  type CodeEdge,
} from "../../src/app/code-pane-layout-model";
import {
  restoreCodePlacement,
  loadCodeLayout,
} from "../../src/app/code-layout-storage";

const reference = JSON.parse(
  readFileSync(
    new URL("../fixtures/code-pane-reference.json", import.meta.url),
    "utf8",
  ),
);
let sequence = 0;
function fromSpec(spec: any): CodeNode {
  if (typeof spec === "string") return { kind: "tile", tileId: spec, flex: 1 };
  if (Array.isArray(spec))
    return { kind: "tile", tileId: spec[0], flex: spec[1] };
  return {
    kind: "stack",
    id: `reference-case-${++sequence}`,
    direction: spec.direction,
    flex: spec.flex ?? 1,
    children: spec.children.map(fromSpec),
  };
}
function shape(node: CodeNode): unknown {
  return node.kind === "tile"
    ? { kind: node.kind, tileId: node.tileId, flex: node.flex }
    : {
        kind: node.kind,
        direction: node.direction,
        flex: node.flex,
        children: node.children.map(shape),
      };
}

test("edge moves match42 cases generated by the actual readable official functions", () => {
  for (const item of reference.cases) {
    let layout = { root: fromSpec(item.spec) } as CodeLayout;
    for (const move of item.moves)
      layout = moveCodeTileToEdge(layout, move.id, move.edge as CodeEdge);
    assert.deepEqual(
      shape(layout.root),
      item.expected,
      JSON.stringify(item.moves),
    );
  }
});
test("minimum-constrained flex resolution matches the official model including narrow fallback", () => {
  for (const item of reference.weights)
    assert.deepEqual(
      resolvedCodeWeights(item.weights, item.mins, item.available),
      item.expected,
    );
});
test("opening uses the source chat2/wide3 ratio, stacks a second tool, then adds another column", () => {
  let layout = initialCodeLayout();
  layout = openCodeTile(layout, "files");
  assert.deepEqual(shape(layout.root), {
    kind: "stack",
    direction: "row",
    flex: 1,
    children: [
      { kind: "tile", tileId: "chat", flex: 2 },
      { kind: "tile", tileId: "files", flex: 3 },
    ],
  });
  layout = openCodeTile(layout, "changes");
  assert.equal(layout.root.children[1].kind, "stack");
  layout = openCodeTile(layout, "browser");
  assert.equal(layout.root.children.length, 3);
  assert.deepEqual(codeTileIds(layout.root), [
    "chat",
    "files",
    "changes",
    "browser",
  ]);
  assert.equal(openCodeTile(layout, "files"), layout);
});
test("moving across chat and perpendicular splitting preserve every pane and immutable input", () => {
  const initial = openCodeTile(
    openCodeTile(initialCodeLayout(), "files"),
    "changes",
  );
  const before = JSON.stringify(initial);
  const left = moveCodeTileToEdge(initial, "files", "left");
  assert.deepEqual(codeTileIds(left.root), ["files", "chat", "changes"]);
  const top = moveCodeTileToEdge(left, "files", "top");
  assert.equal(top.root.direction, "column");
  assert.equal(top.root.children[1].kind, "stack");
  assert.equal(JSON.stringify(initial), before);
  const removed = removeCodeTile(top, "files");
  assert.deepEqual(codeTileIds(removed.root), ["chat", "changes"]);
  assert.equal(removeCodeTile(removed, "chat"), removed);
});
test("recursive rectangles have source12px dividers and resize only the adjacent pair", () => {
  const layout = openCodeTile(
    openCodeTile(initialCodeLayout(), "files"),
    "changes",
  );
  const resolved = resolveCodeLayout(layout, 1400, 900);
  assert.equal(resolved.dividers.length, 2);
  const vertical = resolved.dividers.find((d) => d.direction === "column")!;
  assert.equal(vertical.rect.height, 12);
  const changed = resizeCodeDivider(layout, vertical, 32),
    after = resolveCodeLayout(changed, 1400, 900);
  assert.equal(
    after.rects.get("files")!.height - resolved.rects.get("files")!.height,
    32,
  );
  assert.equal(
    resolved.rects.get("changes")!.height - after.rects.get("changes")!.height,
    32,
  );
  assert.deepEqual(after.rects.get("chat"), resolved.rects.get("chat"));
  const clamped = resolveCodeLayout(
    resizeCodeDivider(layout, vertical, 100000),
    1400,
    900,
  );
  assert.ok(clamped.rects.get("changes")!.height >= 100);
});

test("closing and reopening a pane restores its surviving anchor group and ratio", () => {
  let layout = openCodeTile(
    openCodeTile(initialCodeLayout(), "files"),
    "changes",
  );
  layout = moveCodeTileToEdge(
    moveCodeTileToEdge(layout, "files", "left"),
    "files",
    "top",
  );
  const hint = captureCodePlacement(layout, "files");
  const closed = removeCodeTile(layout, "files");
  const restored = restoreCodePlacement(closed, "files", hint)!;
  assert.deepEqual(shape(restored.root), shape(layout.root));
  assert.equal(
    restoreCodePlacement(closed, "files", { ...hint!, ratio: Infinity }),
    undefined,
  );
  assert.equal(
    restoreCodePlacement(closed, "files", { ...hint!, anchorIds: ["missing"] }),
    undefined,
  );
});
test("account/session layout JSON retains topology and drops duplicate or unknown leaves", () => {
  const layout = openCodeTile(
    openCodeTile(initialCodeLayout(), "files"),
    "changes",
  );
  const saved = JSON.parse(JSON.stringify(layout));
  assert.deepEqual(
    shape(loadCodeLayout(saved, ["files", "changes"])!.root),
    shape(layout.root),
  );
  saved.root.children.push(
    { kind: "tile", tileId: "files", flex: Infinity },
    { kind: "tile", tileId: "unknown", flex: 1 },
  );
  const parsed = loadCodeLayout(saved, ["files", "changes"])!;
  assert.deepEqual(codeTileIds(parsed.root), ["chat", "files", "changes"]);
  assert.equal(loadCodeLayout(null, []), undefined);
  const missing = loadCodeLayout({ root: { tileId: "files", flex: -1 } }, [
    "files",
  ])!;
  assert.deepEqual(
    new Set(codeTileIds(missing.root)),
    new Set(["files", "chat"]),
  );
});
