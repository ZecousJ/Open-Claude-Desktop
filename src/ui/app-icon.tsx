export type AppIconName = keyof typeof icons;

const sizes = { xs: 12, sm: 16, md: 20, lg: 24, xl: 28, xxl: 32 };

/** A size as callers give it: pixels, a named step, or "auto" (20, 16 when compact). */
export function iconPixels(
  size: number | string,
  comfortable = typeof document === "undefined" ||
    document.documentElement?.dataset?.density !== "compact",
) {
  if (typeof size === "number") return size;
  if (size === "auto") return comfortable ? 20 : 16;
  if (size === "auto-sm") return comfortable ? 16 : 12;
  if (size === "auto-lg") return comfortable ? 24 : 20;
  return sizes[size as keyof typeof sizes] ?? Number.parseFloat(size);
}

export function AppIcon({
  name,
  size,
  bold = false,
  animated: _animated,
  className = "",
  ...props
}: Omit<LucideProps, "name" | "size" | "ref"> & {
  name: AppIconName;
  size?: number | string;
  /** Kept for callers; Lucide icons don't animate. */
  animated?: boolean;
  bold?: boolean;
}) {
  const [Glyph, pixels] = icons[name];
  const filled = name.endsWith("Filled");
  return (
    <Glyph
      {...props}
      data-icon={name}
      className={`app-icon${className ? ` ${className}` : ""}`}
      size={size === undefined ? pixels : iconPixels(size)}
      strokeWidth={bold ? 2.25 : 1.75}
      fill={filled ? "currentColor" : "none"}
      aria-hidden={
        props["aria-hidden"] ?? (props["aria-label"] ? undefined : true)
      }
      role={props.role ?? (props["aria-label"] ? "img" : undefined)}
    />
  );
}
