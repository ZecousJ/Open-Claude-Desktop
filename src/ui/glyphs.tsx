import { forwardRef, type SVGProps } from "react";
import { iconPixels } from "./AnthropiconGlyph";
import { workspaceIcon } from "./workspace-icons";

type IconProps = Omit<SVGProps<SVGSVGElement>, "size"> & {
  size?: number | string;
  absoluteStrokeWidth?: boolean;
  animated?: boolean;
  bold?: boolean;
};

function glyph(name: string) {
  const Icon = workspaceIcon(name);
  return forwardRef<SVGSVGElement, IconProps>(function Glyph(
    { size = 20, animated: _animated, bold, strokeWidth, ...props }, ref,
  ) {
    return <Icon ref={ref} aria-hidden="true" {...props} size={iconPixels(size)} strokeWidth={strokeWidth ?? (bold ? 2.4 : 1.8)} />;
  });
}

